def mod_icon(archives, modid, logo):
    source, filename = ICON_TEXTURES.get(modid, (modid, logo))
    if not filename:
        raise ValueError(f"Missing icon selection for {modid}")
    with ZipFile(archives[source]) as jar:
        image = jar.read(filename)
    if not image.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ValueError(f"Expected a packaged PNG for {modid}: {filename}")
    path = DOCS / "assets/mods" / f"{modid}.png"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(image)


