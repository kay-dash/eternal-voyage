def read(path):
    return path.read_text(encoding="utf-8-sig")


def write(relative_path, lines):
    path = DOCS / relative_path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GENERATED + "\n\n" + "\n".join(lines).rstrip() + "\n", encoding="utf-8")


def clean(value):
    return FORMAT_CODE.sub("", value).replace("OMPWorld", "One Piece World")


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def label(value):
    return cell(clean(value)).replace("<", "&lt;").replace(">", "&gt;")


def inline_code(value):
    return "`" + cell(value).replace("`", "'") + "`"


def table(head, rows):
    return ["", "| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |",
            *("| " + " | ".join(map(str, row)) + " |" for row in rows), ""]


def flatten(data, prefix=""):
    for key, value in data.items():
        if key == "desc:" or PRIVATE_KEY.search(key) or re.search(r"single[- _]?player", key, re.I):
            continue
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict) and value:
            yield from flatten(value, path)
        else:
            yield path, value


def player_settings(data, filename):
    if filename == "hakirework-server.toml":
        for section in ("moveBans", "npcFruits", "professions", "nations", "battles"):
            data.pop(section, None)
        data.get("races", {}).pop("disabled", None)
        data.get("awakening", {}).pop("conquerorCrowd", None)
        lineages = data.get("lineages", {})
        data["lineages"] = {key: value for key, value in lineages.items() if not key.endswith("Chance") or value > 0}
        if not data.get("races", {}).get("enabled"):
            data.pop("races", None)
    elif filename == "mineminenomi-server.toml":
        abilities = data.get("Devil Fruits / Abilities", {})
        abilities.pop("Banned Abilities", None)
        fruit_rules = abilities.get("One Fruit Per World", {})
        if fruit_rules.get("One Fruit per World") == "SIMPLE":
            for key in ("Inventory Fruit Limit", "Unable to pickup Devil Fruit as a fruit user"):
                fruit_rules.pop(key, None)
        abilities.get("Haki", {}).pop("Haoshoku Haki Unlock Logic", None)
    elif filename.startswith("inocruise-"):
        for section in ("seaStorm", "seaKing"):
            data.pop(section, None)
        data.get("traits", {}).pop("disabledTraits", None)
    return data


def render_value(value):
    return inline_code(json.dumps(value, ensure_ascii=False))


def toml_config(path):
    if path.name != "fruit-rot.toml":
        return tomllib.loads(read(path))
    # The world mod reads this TOML-named file as a flat key=value properties file.
    return dict(line.split(" = ", 1) for line in read(path).splitlines() if " = " in line and not line.startswith("#"))


