def damage_reference(changes, npc_share):
    names = {}
    for path in sorted((PACK / "mods").glob("*.jar")):
        with ZipFile(path) as jar:
            for filename in jar.namelist():
                if filename.startswith("assets/") and filename.endswith("/lang/en_us.json"):
                    for key, value in json.loads(jar.read(filename)).items():
                        parts = key.split(".")
                        if len(parts) == 3 and parts[0] == "ability" and isinstance(value, str):
                            names[f"{parts[1]}:{parts[2]}"] = value
    lines = ["# Move damage multipliers", "", f"Look up the {len(changes):,} per-move factors shipped with Eternal Voyage.",
             "A factor of 1.65× adds 65% to the damage entering the normal ability calculation. NPCs get "
             f"{npc_share:.0%} of an increase above 1.00×. Reductions carry over in full.", "",
             "Use [Combat stats and Doriki scaling](../../characters/combat-stats.md) for the growth curves, "
             "worked HP examples and how Haki adds to the hit."]
    groups = defaultdict(list)
    for move_id, player in changes.items():
        modid, move = move_id.split(":")
        name = names.get(move_id, move.replace("_", " ").title())
        npc = 1 + (player - 1) * npc_share if player > 1 else player
        groups[modid].append((label(name), inline_code(move_id), f"{player:g}×", f"{npc:g}×"))
    for modid, rows in sorted(groups.items()):
        lines.extend(["", f"## {MOD_CARDS[modid][0]}", "", f"[{MOD_CARDS[modid][0]} overview](../content/{modid}.md)"])
        lines.extend(table(("Move", "Move ID", "Player factor", "NPC factor"), sorted(rows, key=lambda row: row[0].casefold())))
    write("reference/settings/move-damage.md", lines)


def encounter_reference(companion, prison, health_config, doriki_limit, haki_limit):
    def number(value):
        return f"{value:,.3f}".rstrip("0").rstrip(".")

    def scaled_health(doriki):
        knee, middle, peak = (health_config[key] for key in ("knee-doriki", "knee-health", "max-health"))
        if doriki > doriki_limit:
            return peak * doriki / doriki_limit
        if doriki <= knee:
            return max(20, middle * doriki / knee)
        return middle + (peak - middle) * (doriki - knee) / (doriki_limit - knee)

    prison_scale = companion["rescaleImpel"]
    damage = companion["rescaleDamage"] if prison_scale else 1

    def prison_health(doriki):
        return scaled_health(doriki) if prison_scale else max(20, doriki / 40)

    def boss_health_factor(stage):
        start = companion["fruitGrowthFrom"]
        growth = min(1, max(0, (stage - start) / (doriki_limit - start)))
        values = companion["fruitGrowthAtCap"]
        return companion["bossPlayerDamage"] * (1 + (sum(values) / len(values) - 1) * growth)

    def name(identity):
        slug = identity.split(":")[1]
        special = {"don_krieg": "Don Krieg", "mr_5_and_miss_valentine": "Mr. 5 and Miss Valentine"}
        if slug.startswith("mr_") and slug[3:].isdigit():
            return f"Mr. {slug[3:]}"
        return special.get(slug, slug.replace("_", " ").title())

    lines = ["# Bosses and prison guards", "", "[Encounter stats by sea](../../world/encounter-stats.md)", "",
             "## Challenge bosses", "",
             f"Armament and Observation have a floor based on the encounter’s stage as a share of the **{doriki_limit:,} Doriki** "
             f"cap, up to **{haki_limit:,}** in each. Boss health is multiplied by the figures below. Outgoing damage scales "
             "with the encounter’s stage and the boss’s original difficulty, so it varies by fight.",
             "", "Hard rematches use their own stage. Use the normal and Hard columns for their respective fights."]
    stages = companion["bossStages"]
    rows = []
    for identity, stage in stages.items():
        if identity.endswith("_hard"):
            continue
        hard = stages.get(identity + "_hard")
        rows.append((name(identity), number(stage), f"{boss_health_factor(stage):g}×",
                     number(hard) if hard else "—", f"{boss_health_factor(hard):g}×" if hard else "—"))
    lines.extend(table(("Challenge", "Normal stage", "Normal HP factor", "Hard stage", "Hard HP factor"), rows))
    lines.extend(["## Overworld bosses", "",
                  "These values are for the bosses encountered in the world. Their challenge fights use the separate stages above. "
                  "The stage sets the health multiplier and the minimum Armament and Observation."])
    lines.extend(table(("Boss", "Stage Doriki", "Base HP factor", "Minimum Haki per type", "Outgoing damage factor"), (
        (name(identity), number(stage), f"{boss_health_factor(stage):g}×", number(min(stage / doriki_limit, 1) * haki_limit),
         number(scaled_health(stage) / max(20, companion["worldBossDesignDoriki"] / 40)) + "×")
        for identity, stage in companion["worldBosses"].items()
    )))
    lines.extend(["## Impel Down guards and wardens", "",
                  "The table shows health after Doriki scaling and the standard jailer’s hit before target defences. "
                  f"Hooded guards start with **{prison['hoodDoriki']:.0%} more Doriki** than a uniformed jailer on the same floor. "
                  "Haki is the roll range for the floor. The last column shows which guards can use Armament techniques."])
    lines.extend(table(("Floor", "Jailer Doriki", "Uniformed HP", "Standard hit (HP)", "Armour", "Haki",
                        "Armament users (uniform / hood)"), (
        (str(floor), f"{number(lo)}–{number(hi)}", f"{number(prison_health(lo))}–{number(prison_health(hi))}",
         number(attack * damage), number(armour), f"{haki_lo}–{haki_hi}" if haki_lo != haki_hi else str(haki_lo),
         f"{uniform}% / {hood}%")
        for floor, ((lo, hi, attack, armour, haki_lo, haki_hi, _), (uniform, hood))
        in enumerate(zip(prison["jailers"], prison["jailerHaki"], strict=True))
    )))
    chief_factors = prison["chiefHealth"]
    lines.extend(["Head jailers take the top Doriki roll from their floor. "
                  f"Their HP is **{chief_factors[0]:g}×** the floor’s top jailer HP. "
                  f"The Chief of the Guard and the Warden use **{chief_factors[1]:g}×** and **{chief_factors[2]:g}×** "
                  "of the health calculated for their respective Doriki rows.", "",
                  "### Sphinx, Chief of the Guard and Warden"])
    names = {2: "Sphinx", 5: "Chief of the Guard", 6: "Warden"}
    lines.extend(table(("Floor", "Boss", "Configured Doriki", "Effective HP", "Base attack", "Armour", "Haki"), (
        (str(floor), names.get(floor, "Boss tier"), number(doriki),
         number(prison_health(doriki) * {2: 1, 5: chief_factors[1], 6: chief_factors[2]}[floor]) if floor in names else "—",
         number(attack), number(armour), number(haki))
        for floor, (doriki, attack, armour, haki) in enumerate(prison["bosses"])
    )))
    lines.extend(["### Great beasts", "",
                  f"Rescaled prison enemies deal **{damage:g}×** their configured damage before other combat modifiers. "
                  "The following are floor tiers. Individual beasts can use their own attacks."])
    lines.extend(table(("Floor", "Configured Doriki", "Effective HP from Doriki", "Base attack", "Armour", "Haki"), (
        (str(floor), number(doriki), number(prison_health(doriki)), number(attack), number(armour), number(haki))
        for floor, (doriki, attack, armour, haki) in enumerate(prison["beasts"])
    )))
    write("reference/settings/encounters.md", lines)



def quest_records(path):
    text = read(path)
    title = json.loads(re.search(r'^\ttitle: (".*")$', text, re.M)[1])
    quests = []
    for block in re.findall(r"^\t\t\{\n(.*?)^\t\t\}", text, re.M | re.S):
        fields = dict(re.findall(r"^\t{3}(\w+): (.*)$", block, re.M))
        if "title" not in fields:
            continue
        record = {
            "id": json.loads(fields["id"]),
            "title": clean(json.loads(fields["title"])),
            "optional": fields.get("optional") == "true",
            "dependency_requirement": fields.get("dependency_requirement"),
            "minimum": fields.get("min_required_dependencies"),
            "dependencies": re.findall(r'"([0-9A-F]+)"', fields.get("dependencies", "")),
        }
        description = re.search(r"^\t{3}description: \[\n(.*?)^\t{3}\]", block, re.M | re.S)
        record["description"] = [
            clean(json.loads(line.strip())) for line in description[1].splitlines() if line.strip().startswith('"')
        ] if description else []
        for section in ("tasks", "rewards"):
            match = re.search(rf"^\t{{3}}{section}: \[\n(.*?)^\t{{3}}\]", block, re.M | re.S)
            record[section] = re.findall(r'^\t{5}title: (".*")$', match[1], re.M) if match else []
        quests.append(record)
    return title, quests


